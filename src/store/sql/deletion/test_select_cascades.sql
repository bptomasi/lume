SELECT
    (SELECT count(*) FROM articles) = 1 AS articles,
    (SELECT count(*) FROM article_documents) = 1 AS documents,
    (SELECT count(*) FROM comments) = 1 AS comments,
    (SELECT count(*) FROM study_cards) = 1 AS cards,
    (SELECT count(*) FROM annotation_reviews) = 1 AS reviews,
    (SELECT count(*) FROM note_versions) = 1 AS versions,
    (SELECT count(*) FROM note_metadata) = 1 AS metadata,
    (SELECT count(*) FROM note_export_manifest) = 1 AS note_exports,
    (SELECT count(*) FROM export_manifest) = 1 AS exports,
    (SELECT count(*) FROM members) = 1 AS memberships,
    (SELECT count(*) FROM note_drafts) = 1 AS drafts,
    (SELECT count(*) FROM note_links) = 0 AS linked_articles,
    (SELECT count(*) FROM note_references) = 0 AS references_between_notes,
    (SELECT count(*) FROM article_tags) = 1 AS article_tags,
    (SELECT count(*) FROM comment_tags) = 1 AS comment_tags,
    (SELECT count(*) FROM recommendation_features) = 1 AS recommendation_features,
    (SELECT count(*) FROM recommendation_matches) = 1 AS recommendation_matches,
    (SELECT count(*) FROM recommendation_items) = 1 AS recommendation_items,
    (SELECT count(*) FROM recommendation_feedback) = 1 AS feedback,
    (SELECT count(*) FROM recommendation_feedback_topics) = 1 AS feedback_topics,
    (SELECT count(*) FROM recommendation_dirty) = 1 AS recommendation_dirty,
    (SELECT count(*) FROM image_reference_dirty) = 1 AS image_queue,
    (SELECT count(*) FROM server_entries) = 0 AS remote_aliases,
    (SELECT count(*) FROM retention_tombstones) = 2 AS suppressed_aliases,
    (SELECT count(*) FROM article_search WHERE article_search MATCH 'purgedfeed OR purgedfull') = 0 AS article_search,
    (SELECT count(*) FROM note_search WHERE note_search MATCH 'purgednote') = 0 AS note_search,
    (SELECT count(*) FROM article_search WHERE article_search MATCH 'survivingfeed') = 1 AS surviving_search;
